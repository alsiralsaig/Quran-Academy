// Multi-tier Gemini Service with direct REST fallback and offline Islamic knowledge base

const getApiKey = (): string => {
  if (typeof window !== 'undefined') {
    const local = localStorage.getItem('gemini_api_key');
    if (local && local.trim().length > 10) return local.trim();
  }
  return (
    (import.meta as any).env?.VITE_GEMINI_API_KEY ||
    (import.meta as any).env?.GEMINI_API_KEY ||
    (typeof process !== 'undefined' && process.env?.GEMINI_API_KEY) ||
    ''
  );
};

export async function askQuranAssistant(prompt: string, context?: string): Promise<string> {
  const apiKey = getApiKey();
  const trimmedPrompt = prompt.trim();

  // If API Key is available, attempt live Gemini API call
  if (apiKey) {
    try {
      const systemInstruction = `
أنت "مساعد إتقان الذكي" - معلم قرآني ومستشار تربوي خبير في أحكام التجويد، والتفسير الميسر، وطرق تحفيظ القرآن الكريم ومراجعته.
مهامك:
1. إجابة أسئلة الطلاب والمعلمات بأدب ووقار وبلغة عربية فصيحة وميسرة.
2. توضيح أحكام التجويد (كالنون الساكنة والتنوين، المدود، القلقلة، المخارج والصفات) بالأمثلة القرآنية الواضحة.
3. تقديم جداول مراجعة وحفظ مقترحة ومناسبة لكل مرحلة.
4. الإجابة بتنظيم ورؤوس أقلام واضحة ومحفزة.
      `.trim();

      const fullPrompt = context 
        ? `${systemInstruction}\n\nالسياق: ${context}\n\nسؤال المستخدم: ${trimmedPrompt}`
        : `${systemInstruction}\n\nسؤال المستخدم: ${trimmedPrompt}`;

      // Try Gemini 1.5 Flash / 2.0 Flash REST endpoint
      const models = ['gemini-1.5-flash', 'gemini-2.0-flash', 'gemini-1.5-pro'];
      for (const model of models) {
        try {
          const res = await fetch(`https://generativelanguage.googleapis.com/v1beta/models/${model}:generateContent?key=${apiKey}`, {
            method: 'POST',
            headers: { 'Content-Type': 'application/json' },
            body: JSON.stringify({
              contents: [{ parts: [{ text: fullPrompt }] }],
              generationConfig: { temperature: 0.7 }
            })
          });

          if (res.ok) {
            const data = await res.json();
            const text = data?.candidates?.[0]?.content?.parts?.[0]?.text;
            if (text && text.trim()) {
              return text.trim();
            }
          }
        } catch (e) {
          console.warn(`Model ${model} fetch error:`, e);
        }
      }
    } catch (err) {
      console.error('Gemini API call failed:', err);
    }
  }

  // Smart Pre-built Quranic & Tajweed Knowledge Engine
  return getSmartQuranicKnowledgeResponse(trimmedPrompt);
}

// Built-in intelligent Islamic knowledge engine
function getSmartQuranicKnowledgeResponse(query: string): string {
  const q = query.toLowerCase();

  // 1. أحكام النون الساكنة والتنوين / التجويد
  if (q.includes('تجويد') || q.includes('إدغام') || q.includes('إظهار') || q.includes('إخفاء') || q.includes('إقلاب') || q.includes('نون ساكنة')) {
    return `📖 *أحكام النون الساكنة والتنوين الأربعة في علم التجويد:*

1️⃣ **الإظهار الحلقي:**
• تعريفه: إخراج النون أو التنوين واضحة بدون غنة زائدة.
• حروفه (6): (ء، هـ، ع، ح، غ، خ) مجموعة في: "أخي هاك علماً حازه غير خاسر".
• مثال: ﴿مِنْ هَادٍ﴾، ﴿عَلِيمٌ حَكِيمٌ﴾.

2️⃣ **الإدغام:**
• تعريفه: إدخال النون الساكنة أو التنوين في الحرف الذي بعدها.
• حروفه (6): مجموعة في كلمة (يَرْمَلُون).
• ينقسم إلى:
   - **إدغام بغنة** (ي، ن، م، و): ﴿مَن يَقُولُ﴾، ﴿مِن مَّالٍ﴾.
   - **إدغام بغير غنة** (ل، ر): ﴿مِن رَّبِّهِمْ﴾، ﴿هُدًى لِّلْمُتَّقِينَ﴾.

3️⃣ **الإقلاب:**
• تعريفه: قلب النون الساكنة أو التنوين ميماً مخفاة مع الغنة عند حرف (الباء).
• مثال: ﴿مِن بَعْدِ﴾، ﴿سَمِيعٌ بَصِيرٌ﴾.

4️⃣ **الإخفاء الحقيقي:**
• تعريفه: النطق بالنون بين الإظهار والإدغام مع بقاء الغنة.
• حروفه: باقي الحروف الـ 15 (ص، ذ، ث، ك، ج، ش، ق، س، د، ط، ز، ف، ت، ض، ظ).
• مثال: ﴿مِن شَرِّ﴾، ﴿كِتَابٌ كَرِيمٌ﴾.`;
  }

  // 2. القلقلة والمدود
  if (q.includes('قلقلة') || q.includes('مدود') || q.includes('مد')) {
    return `💎 *أحكام القلقلة والمدود في التجويد:*

🟢 **أحكام القلقلة:**
• حروفها (5): مجموعة في عبارة (قُطْبُ جَدٍّ).
• شروطها: أن يكون الحرف ساكناً سكوناً أصلياً أو عارضاً للوقف.
• مراتبها:
  1. *كبرى*: عند الوقف على الحرف المشدد ﴿وَتَبَّ﴾.
  2. *وسطى*: عند الوقف على الحرف الساكن المخفف ﴿الْفَلَقِ﴾.
  3. *صغرى*: في وسط الكلمة أو الكلام ﴿يَطْمَعُ﴾، ﴿يَجْعَلُونَ﴾.

🟡 **أحكام المدود الرئيسية:**
• حروف المد (3): (الألف الساكنة المفتوح ما قبلها، الواو الساكنة المضموم ما قبلها، الياء الساكنة المكسور ما قبلها).
• *المد الطبيعي*: مقداره حركتان مثل: ﴿قَالَ﴾، ﴿يَقُولُ﴾.
• *المد الواجب المتصل*: حرف المد والهمز في كلمة واحدة (4-5 حركات) مثل: ﴿جَآءَ﴾.
• *المد الجائز المنفصل*: حرف المد في آخر كلمة والهمز في أول الكلمة التالية (4-5 حركات) مثل: ﴿إِنَّآ أَعْطَيْنَاكَ﴾.
• *المد اللازم*: أن يأتي بعد حرف المد سكون أصلي (6 حركات لزوماً) مثل: ﴿الصَّآخَّةُ﴾، ﴿الضَّآلِّينَ﴾.`;
  }

  // 3. جدول مراجعة جزء عم وجزء تبارك
  if (q.includes('جدول') || q.includes('مراجعة') || q.includes('عم') || q.includes('تبارك') || q.includes('خطة')) {
    return `🗓️ *جدول مقترح ومتقن لمراجعة جزء عمّ وجزء تبارك (خلال 10 أيام):*

• **اليوم 1:** مراجعة سورة النبأ والنازعات + تكرار كل سورة 3 مرات.
• **اليوم 2:** مراجعة من سورة عبس إلى سورة المطففين + ربطها باليوم الأول.
• **اليوم 3:** مراجعة من سورة الانشقاق إلى سورة الطارق + اختبار ذاتي.
• **اليوم 4:** مراجعة من سورة الأعلى إلى سورة الفجر + ضبط مواضع الوقف.
• **اليوم 5:** مراجعة من سورة البلد إلى سورة الناس + سرد جزء عمّ كاملاً غيباً.
• **اليوم 6:** مراجعة سورتي الملك والقلم (جزء تبارك).
• **اليوم 7:** مراجعة سورتي الحاقة والمعارج.
• **اليوم 8:** مراجعة سورتي نوح والجن.
• **اليوم 9:** مراجعة من سورة المزمل إلى سورة المرسلات.
• **اليوم 10:** اختبار شامل وتسميع لجزء تبارك كاملاً.

💡 *نصيحة الإتقان:* قسّم المراجعة إلى (مراجعة قريبة للربط) صباحاً، و(مراجعة بعيدة للتثبيت) بعد صلاة العصر أو المغرب.`;
  }

  // 4. المتشابهات اللفظية
  if (q.includes('متشابه') || q.includes('متشابهات') || q.includes('تثبيت') || q.includes('البقرة')) {
    return `🔍 *أهم القواعد الذهبية لضبط المتشابهات اللفظية:*

1️⃣ **قاعدة العناية بما زاد في المبنى:**
• الزيادة في اللفظ تفيد الزيادة في المعنى، مثل قوله تعالى في البقرة: ﴿فَأَزَلَّهُمَا﴾ وفي الأعراف: ﴿فَوَسْوَسَ لَهُمَا﴾.

2️⃣ **قاعدة الترتيب الهجائي والأسبقية:**
• في سورة البقرة: ﴿يُبَصَّرُونَهُمْ﴾، وفي سورة آل عمران تقديم ما يناسب سياق السورة.

3️⃣ **قاعدة ربط المتشابه باسم السورة أو سياقها:**
• تذكر الآية بما يناسب محور السورة (مثلاً سورة البقرة موضوعها الاستخلاف، وآل عمران الثبات والدعوة).

4️⃣ **المقارنة والمقابلة وكتابة المتشابهات:**
• خصص دفتراً لتدوين الآيات المتشابهة في عمودين مع تمييز الكلمة المختلفة بلون مغاير.`;
  }

  // 5. تفسير سورة الكهف
  if (q.includes('كهف') || q.includes('تفسير')) {
    return `💡 *وقفات وتدبر ميسر في سورة الكهف والدروس المستفادة منها:*

✨ **القصص الأربع الرئيسية في السورة والفتن التي تعالجها:**
1. **قصة أصحاب الكهف:** النجاة من *فتنة الدين* باللجوء إلى الله والاعتصام بالصحبة الصالحة.
2. **قصة صاحب الجنتين:** النجاة من *فتنة المال* بتذكر زوال النعم وقول ﴿مَا شَاءَ اللَّهُ لَا قُوَّةَ إِلَّا بِاللَّهِ﴾.
3. **قصة موسى والخضر:** النجاة من *فتنة العلم* بالتواضع وإدراك حكمة الأقدار الخفية.
4. **قصة ذي القرنين:** النجاة من *فتنة السلطة والتمكين* بالعدل وبناء الحضارة وإخلاص العمل.

🌟 **محور السورة الأساسي:** الثبات على العقيدة والاستعانة بالله ﴿فَمَن كَانَ يَرْجُو لِقَاءَ رَبِّهِ فَلْيَعْمَلْ عَمَلًا صَالِحًا وَلَا يُشْرِكْ بِعِبَادَةِ رَبِّهِ أَحَدًا﴾.`;
  }

  // الإجابة العامة الشاملة
  return `🌿 *أهلاً بك في أكاديمية إتقان لتحفيظ القرآن الكريم!*

يسعدني دائماً مساعدتك في:
1. **شرح أحكام التجويد ومخارج الحروف مع الأمثلة.**
2. **تجهيز جداول الحفظ والمراجعة اليومية والأسبوعية.**
3. **ضبط المتشابهات وتثبيت الآيات والسور الطويلة.**
4. **التفسير الميسر والتدبر القرآني.**

تفضل بكتابة سؤالك بالتفصيل (مثل: أحكام الإدغام، جدول مراجعة، أو تفسير آية محددة) وسأجيبك فوراً! 📖✨`;
}

export async function generateMemorizationSchedule(params: {
  currentMemorized: string;
  dailyMinutes: number;
  targetGoal: string;
}): Promise<string> {
  const prompt = `
أنشئ جدولاً تحفيزياً ومفصلاً لمدة أسبوع واحد لمسار حفظ ومراجعة القرآن الكريم:
- الحفظ الحالي: ${params.currentMemorized}
- الوقت اليومي المتاح: ${params.dailyMinutes} دقيقة
- الهدف المنشود: ${params.targetGoal}
  `.trim();

  return askQuranAssistant(prompt);
}
